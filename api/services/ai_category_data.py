_VALID_CONDITION_LABELS = {
    "отличное": "Отличное",
    "хорошее": "Хорошее",
    "удовлетворительное": "Удовлетворительное",
    "требует внимания": "Требует внимания",
    "excellent": "Отличное",
    "good": "Хорошее",
    "fair": "Удовлетворительное",
    "poor": "Требует внимания",
}


def detect_category(title: str, parameters: list[dict] | None = None) -> str:
    """Detect product category from title and parameters."""
    text = title.lower()
    # Also check parameter values for auto-specific fields
    if parameters:
        param_text = " ".join(str(p.get("value", "")) for p in parameters).lower()
        text = f"{text} {param_text}"

    # Sub-categories that should win over their parent category even when
    # the parent has more keyword matches.  E.g. "Чехол для iPhone 14 Pro
    # Max" matches both phone_accessory (1) and phone (2), but the item
    # is clearly an accessory, not a phone.
    _SUBCATEGORY_BOOST: dict[str, float] = {  # noqa: N806
        "phone_accessory": 3.0,
        "auto_accessory": 3.0,
        "computer_accessory": 3.0,
        "photo_accessory": 3.0,
        "gaming_accessory": 3.0,
        "home_accessory": 3.0,
        "bicycle_accessory": 3.0,
        "watch_accessory": 3.0,
    }

    best_match = "default"
    best_count = 0.0
    for category, keywords in CATEGORY_KEYWORDS.items():
        matches = sum(1 for kw in keywords if kw in text)
        score = matches * _SUBCATEGORY_BOOST.get(category, 1.0)
        if score > best_count:
            best_count = score
            best_match = category
    return best_match



def normalize_condition_label(value: str | None) -> str:
    """Normalize a free-form condition label into one of the valid options.

    Returns one of: "Отличное", "Хорошее", "Удовлетворительное",
    "Требует внимания", or "" if no match.
    """
    text = str(value or "").strip()
    if not text:
        return ""
    normalized = text.lower()
    if "|" in normalized:
        for token in ("хорошее", "удовлетворительное", "требует внимания", "отличное"):
            if token in normalized:
                return _VALID_CONDITION_LABELS[token]
    for key, label in _VALID_CONDITION_LABELS.items():
        if key == normalized or key in normalized:
            return label
    return ""


# Backwards-compat alias — kept temporarily so external imports don't break.
# Prefer normalize_condition_label going forward.
_normalize_condition_label = normalize_condition_label

